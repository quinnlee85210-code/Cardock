class CustomThemeEditorPage extends StatefulWidget {
  const CustomThemeEditorPage({
    required this.controller,
    required this.accountCount,
    required this.subscriptionCount,
    required this.renewalsWithinThirtyDays,
    super.key,
  });

  final CardockAppearanceController controller;
  final int accountCount;
  final int subscriptionCount;
  final int renewalsWithinThirtyDays;

  @override
  State<CustomThemeEditorPage> createState() => _CustomThemeEditorPageState();
}

class _CustomThemeEditorPageState extends State<CustomThemeEditorPage> {
  late CardockCustomTheme _draft;
  CardockCustomTheme? _undoDraft;
  Brightness _editingBrightness = Brightness.light;
  bool _advancedUnlocked = false;
  bool _saving = false;

  @override
  void initState() {
    super.initState();
    _draft = widget.controller.preferences.customTheme;
  }

  CardockCustomColors get _colors => _draft.colorsFor(_editingBrightness);

  bool get _dirty => _draft != widget.controller.preferences.customTheme;

  void _setDraft(CardockCustomTheme next, {bool recordUndo = true}) {
    if (next == _draft) return;
    setState(() {
      if (recordUndo) _undoDraft = _draft;
      _draft = next;
    });
  }

  void _replaceColors(CardockCustomColors colors) {
    _setDraft(
      _editingBrightness == Brightness.dark
          ? _draft.copyWith(dark: colors)
          : _draft.copyWith(light: colors),
    );
  }

  void _beginQuickGesture() {
    setState(() => _undoDraft = _draft);
  }

  void _applyQuickSettings(
    CardockCustomQuickSettings quickSettings, {
    bool recordUndo = true,
  }) {
    final generated = cardockGenerateQuickTheme(
      quickSettings: quickSettings,
      launcherFallback: _draft.launcherFallback,
    );
    _setDraft(generated, recordUndo: recordUndo);
  }

  void _undo() {
    final previous = _undoDraft;
    if (previous == null) return;
    setState(() {
      _draft = previous;
      _undoDraft = null;
    });
    _message('已撤销上一次配色调整。');
  }

  void _resetGroup(_CustomColorGroup group) {
    final next = cardockResetCustomGroup(
      _draft,
      brightness: _editingBrightness,
      group: group.model,
    );
    _setDraft(next);
    _message(
      context.tr('已重置{mode}·{group}。', <String, Object?>{
        'mode': context.tr(_editingBrightness == Brightness.dark ? '深色' : '浅色'),
        'group': context.tr(group.label),
      }),
    );
  }

  Future<void> _editColor(_CustomColorToken token) async {
    final selected = await showDialog<Color>(
      context: context,
      builder: (context) => _ColorPickerDialog(
        title: token.label,
        initialColor: token.read(_colors),
      ),
    );
    if (selected == null) return;
    _replaceColors(token.write(_colors, selected));
  }

  void _autoGenerateDark() {
    final generated = _generateDarkColors(_draft.light);
    final candidate = _draft.copyWith(dark: generated);
    final hasDarkIssue = candidate.validate().any(
      (issue) => issue.token.startsWith('dark.'),
    );
    _setDraft(
      _draft.copyWith(
        dark: hasDarkIssue ? CardockCustomTheme.defaults.dark : generated,
      ),
    );
    setState(() {
      _editingBrightness = Brightness.dark;
    });
    _message(
      hasDarkIssue ? '已生成安全的深色起点；原浅色组合无法完整保留对比度。' : '已按浅色配色生成深色起点，可继续逐项调整。',
    );
  }

  Future<void> _resetCustomDefaults() async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('恢复自定义默认值？'),
        content: const Text(
          '只重置自定义主题的浅色、深色和跟随主题时的桌面图标回退；'
          '八套固定主题不受影响。保存后才会生效。',
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('取消'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, true),
            child: const Text('恢复'),
          ),
        ],
      ),
    );
    if (confirmed != true || !mounted) return;
    _setDraft(CardockCustomTheme.defaults);
    setState(() {
      _advancedUnlocked = false;
    });
  }

  Future<void> _save() async {
    if (_saving) return;
    final entitlement = ProductEntitlementScope.of(context).value;
    if (!const EntitlementGuard().canUseTheme(
      entitlement: entitlement,
      family: CardockThemeFamily.custom,
    )) {
      await showFullVersionUpsell(
        context,
        scene: FullVersionUpsellScene.premiumTheme,
      );
      return;
    }
    final issues = _draft.validate();
    if (issues.isNotEmpty) {
      await _showValidationIssues(issues);
      return;
    }
    setState(() => _saving = true);
    try {
      await widget.controller.setCustomTheme(_draft);
      if (!mounted) return;
      setState(() {
        _draft = widget.controller.preferences.customTheme;
        _undoDraft = null;
      });
      _message('自定义主题已安全保存。');
    } on Object {
      if (mounted) {
        _message('自定义主题写入失败，原设置保持不变。');
      }
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }

  Future<void> _showValidationIssues(List<CardockContrastIssue> issues) async {
    await showDialog<void>(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('这些颜色暂时不能保存'),
        content: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 440, maxHeight: 420),
          child: SingleChildScrollView(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              mainAxisSize: MainAxisSize.min,
              children: [
                const Text('请调整以下具体颜色，使文字、图标和交互控件保持清晰：'),
                const SizedBox(height: 12),
                for (final issue in issues.take(12)) ...[
                  Text(
                    _issueLabel(context, issue.token),
                    style: const TextStyle(fontWeight: FontWeight.w700),
                  ),
                  Text(
                    context.tr(
                      '前景 {foreground} / 背景 {background}',
                      <String, Object?>{
                        'foreground': issue.foregroundHex,
                        'background': issue.backgroundHex,
                      },
                    ),
                    translate: false,
                  ),
                  Text(
                    context.tr(
                      '当前 {ratio}:1，至少 {required}:1；建议起点 {recommended}',
                      <String, Object?>{
                        'ratio': issue.ratio.toStringAsFixed(2),
                        'required': issue.required.toStringAsFixed(1),
                        'recommended': issue.recommendedHex,
                      },
                    ),
                    translate: false,
                  ),
                  const SizedBox(height: 6),
                ],
                if (issues.length > 12)
                  Text(
                    context.tr('另有 {count} 项，请继续调整后再次保存。', <String, Object?>{
                      'count': issues.length - 12,
                    }),
                    translate: false,
                  ),
              ],
            ),
          ),
        ),
        actions: [
          TextButton.icon(
            key: const ValueKey<String>('custom-theme-auto-fix'),
            onPressed: () {
              final repaired = cardockAutoFixCustomTheme(_draft);
              Navigator.pop(context);
              _setDraft(repaired);
              _message('已自动修正失败组合，可使用撤销恢复。');
            },
            icon: const Icon(Icons.auto_fix_high_outlined),
            label: const Text('自动修正'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('返回调整'),
          ),
        ],
      ),
    );
  }

  void _message(String text) {
    if (!mounted) return;
    ScaffoldMessenger.of(context)
      ..hideCurrentSnackBar()
      ..showSnackBar(SnackBar(content: Text(context.tr(text))));
  }

  @override
  Widget build(BuildContext context) {
    final issues = _draft.validate();
    return Scaffold(
      appBar: AppBar(
        title: const Text('自定义主题'),
        actions: [
          IconButton(
            key: const ValueKey<String>('custom-theme-undo'),
            tooltip: context.tr('撤销上一次调整'),
            onPressed: _undoDraft == null ? null : _undo,
            icon: const Icon(Icons.undo_rounded),
          ),
          TextButton(
            key: const ValueKey<String>('custom-theme-save'),
            onPressed: _saving || !_dirty || issues.isNotEmpty ? null : _save,
            child: const Text('保存'),
          ),
          const SizedBox(width: 8),
        ],
      ),
      body: ListView(
        key: const ValueKey<String>('custom-theme-editor-page'),
        padding: const EdgeInsets.fromLTRB(
          CardockLayout.screenHorizontal,
          8,
          CardockLayout.screenHorizontal,
          40,
        ),
        children: [
          _CustomThemePreview(colors: _colors, brightness: _editingBrightness),
          const SizedBox(height: 18),
          SingleChildScrollView(
            scrollDirection: Axis.horizontal,
            child: SegmentedButton<Brightness>(
              key: const ValueKey<String>('custom-theme-brightness'),
              segments: const [
                ButtonSegment<Brightness>(
                  value: Brightness.light,
                  label: Text('浅色'),
                  icon: Icon(Icons.light_mode_outlined),
                ),
                ButtonSegment<Brightness>(
                  value: Brightness.dark,
                  label: Text('深色'),
                  icon: Icon(Icons.dark_mode_outlined),
                ),
              ],
              selected: <Brightness>{_editingBrightness},
              showSelectedIcon: false,
              onSelectionChanged: (selection) {
                if (selection.isNotEmpty) {
                  setState(() => _editingBrightness = selection.first);
                }
              },
            ),
          ),
          const SizedBox(height: 10),
          Align(
            alignment: Alignment.centerRight,
            child: TextButton.icon(
              key: const ValueKey<String>('custom-theme-auto-dark'),
              onPressed: _autoGenerateDark,
              icon: const Icon(Icons.auto_awesome_outlined),
              label: const Text('由浅色生成深色'),
            ),
          ),
          const SizedBox(height: 10),
          _QuickControlsCard(
            settings: _draft.quickSettings,
            onHueChangeStart: _beginQuickGesture,
            onHueChanged: (value) => _applyQuickSettings(
              _draft.quickSettings.copyWith(accentHue: value),
              recordUndo: false,
            ),
            onChanged: _applyQuickSettings,
          ),
          if (issues.isNotEmpty) ...[
            const SizedBox(height: 8),
            _ValidationBanner(
              issues: issues,
              onReview: () => _showValidationIssues(issues),
            ),
          ],
          const SizedBox(height: 18),
          _LauncherFallbackCard(
            selected: _draft.launcherFallback,
            onChanged: (value) {
              _setDraft(_draft.copyWith(launcherFallback: value));
            },
          ),
          const SizedBox(height: 24),
          Card(
            clipBehavior: Clip.antiAlias,
            child: ExpansionTile(
              key: const ValueKey<String>('custom-theme-advanced-editor'),
              initiallyExpanded: false,
              leading: const Icon(Icons.tune_rounded),
              title: const Text('进阶模块编辑'),
              subtitle: const Text('七组 Token · 状态色默认锁定'),
              childrenPadding: const EdgeInsets.fromLTRB(12, 0, 12, 16),
              children: [
                for (final group in _CustomColorGroup.values) ...[
                  _ColorGroupCard(
                    group: group,
                    colors: _colors,
                    advancedUnlocked: _advancedUnlocked,
                    onToggleAdvanced: group == _CustomColorGroup.semanticStates
                        ? () => setState(
                            () => _advancedUnlocked = !_advancedUnlocked,
                          )
                        : null,
                    onEdit: _editColor,
                    onReset: () => _resetGroup(group),
                  ),
                  const SizedBox(height: 18),
                ],
              ],
            ),
          ),
          const SizedBox(height: 18),
          OutlinedButton.icon(
            key: const ValueKey<String>('custom-theme-reset'),
            onPressed: _resetCustomDefaults,
            icon: const Icon(Icons.restart_alt_rounded),
            label: const Text('恢复自定义默认值'),
          ),
          if (_saving) ...[
            const SizedBox(height: 16),
            const LinearProgressIndicator(),
          ],
        ],
      ),
    );
  }
}

