class _ColorPickerDialogState extends State<_ColorPickerDialog> {
  late HSVColor _hsv;
  late final TextEditingController _hexController;
  bool _validHex = true;

  @override
  void initState() {
    super.initState();
    _hsv = HSVColor.fromColor(widget.initialColor);
    _hexController = TextEditingController(text: _hex(widget.initialColor));
  }

  @override
  void dispose() {
    _hexController.dispose();
    super.dispose();
  }

  void _setHsv(HSVColor next) {
    setState(() {
      _hsv = next;
      _validHex = true;
      _hexController.text = _hex(next.toColor());
    });
  }

  void _setHex(String raw) {
    final parsed = _parseHex(raw);
    setState(() {
      _validHex = parsed != null;
      if (parsed != null) _hsv = HSVColor.fromColor(parsed);
    });
  }

  @override
  Widget build(BuildContext context) {
    final color = _hsv.toColor();
    return AlertDialog(
      title: Text(context.tr(widget.title), translate: false),
      content: ConstrainedBox(
        constraints: const BoxConstraints(maxWidth: 420),
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Container(
                key: const ValueKey<String>('custom-color-preview'),
                height: 70,
                decoration: BoxDecoration(
                  color: color,
                  borderRadius: BorderRadius.circular(CardockRadius.control),
                  border: Border.all(color: Theme.of(context).dividerColor),
                ),
              ),
              const SizedBox(height: 16),
              TextField(
                key: const ValueKey<String>('custom-color-hex'),
                controller: _hexController,
                textCapitalization: TextCapitalization.characters,
                inputFormatters: [
                  FilteringTextInputFormatter.allow(RegExp(r'[#0-9a-fA-F]')),
                  LengthLimitingTextInputFormatter(7),
                ],
                decoration: InputDecoration(
                  labelText: context.tr('HEX 颜色'),
                  hintText: '#5967E8',
                  errorText: _validHex ? null : context.tr('请输入 #RRGGBB'),
                ),
                onChanged: _setHex,
              ),
              const SizedBox(height: 12),
              _ColorSlider(
                label: '色相',
                value: _hsv.hue,
                max: 360,
                onChanged: (value) => _setHsv(_hsv.withHue(value)),
              ),
              _ColorSlider(
                label: '饱和度',
                value: _hsv.saturation * 100,
                max: 100,
                onChanged: (value) => _setHsv(_hsv.withSaturation(value / 100)),
              ),
              _ColorSlider(
                label: '明度',
                value: _hsv.value * 100,
                max: 100,
                onChanged: (value) => _setHsv(_hsv.withValue(value / 100)),
              ),
            ],
          ),
        ),
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.pop(context),
          child: const Text('取消'),
        ),
        FilledButton(
          key: const ValueKey<String>('custom-color-confirm'),
          onPressed: _validHex ? () => Navigator.pop(context, color) : null,
          child: const Text('确定'),
        ),
      ],
    );
  }
}

