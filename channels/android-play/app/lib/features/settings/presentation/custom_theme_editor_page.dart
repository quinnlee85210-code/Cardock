CardockCustomColors _generateDarkColors(CardockCustomColors source) {
  final target = CardockCustomTheme.defaults.dark;
  Color adapt(Color color, Color targetColor) {
    final sourceHsv = HSVColor.fromColor(color);
    final targetHsv = HSVColor.fromColor(targetColor);
    return targetHsv
        .withHue(sourceHsv.hue)
        .withSaturation(
          (sourceHsv.saturation * 0.7 + targetHsv.saturation * 0.3).clamp(0, 1),
        )
        .toColor();
  }

  return CardockCustomColors(
    background: adapt(source.background, target.background),
    surface: adapt(source.surface, target.surface),
    surfaceAlt: adapt(source.surfaceAlt, target.surfaceAlt),
    text: adapt(source.text, target.text),
    textSecondary: adapt(source.textSecondary, target.textSecondary),
    border: adapt(source.border, target.border),
    brandPrimary: adapt(source.brandPrimary, target.brandPrimary),
    brandSecondary: adapt(source.brandSecondary, target.brandSecondary),
    navigationActive: adapt(source.navigationActive, target.navigationActive),
    focus: adapt(source.focus, target.focus),
    overviewStart: adapt(source.overviewStart, target.overviewStart),
    overviewEnd: adapt(source.overviewEnd, target.overviewEnd),
    currencyAccent: adapt(source.currencyAccent, target.currencyAccent),
    accountAccent: adapt(source.accountAccent, target.accountAccent),
    accountIconBackground: adapt(
      source.accountIconBackground,
      target.accountIconBackground,
    ),
    fieldLogin: adapt(source.fieldLogin, target.fieldLogin),
    fieldPhone: adapt(source.fieldPhone, target.fieldPhone),
    fieldEmail: adapt(source.fieldEmail, target.fieldEmail),
    fieldPassword: adapt(source.fieldPassword, target.fieldPassword),
    fieldUrl: adapt(source.fieldUrl, target.fieldUrl),
    subscriptionAccent: adapt(
      source.subscriptionAccent,
      target.subscriptionAccent,
    ),
    renewalAccent: adapt(source.renewalAccent, target.renewalAccent),
    subscriptionIconBackground: adapt(
      source.subscriptionIconBackground,
      target.subscriptionIconBackground,
    ),
    actionPrimary: adapt(source.actionPrimary, target.actionPrimary),
    actionSecondary: adapt(source.actionSecondary, target.actionSecondary),
    inputFocus: adapt(source.inputFocus, target.inputFocus),
    success: adapt(source.success, target.success),
    warning: adapt(source.warning, target.warning),
    danger: adapt(source.danger, target.danger),
    paused: adapt(source.paused, target.paused),
    neutral: adapt(source.neutral, target.neutral),
  );
}

Color? _parseHex(String value) {
  if (!RegExp(r'^#[0-9A-Fa-f]{6}$').hasMatch(value)) return null;
  return Color(int.parse('FF${value.substring(1)}', radix: 16));
}

String _hex(Color color) {
  final rgb = color.toARGB32() & 0x00FFFFFF;
  return '#${rgb.toRadixString(16).padLeft(6, '0').toUpperCase()}';
}

String _issueLabel(BuildContext context, String token) {
  final mode = token.startsWith('dark.') ? '深色' : '浅色';
  final normalized = token.replaceFirst(RegExp(r'^(light|dark)\.'), '');
  final labels = <String, String>{
    'foundation': '基础界面',
    'brandNavigation': '品牌与导航',
    'homeOverview': '首页总览',
    'accounts': '账号模块',
    'subscriptions': '订阅模块',
    'formsActions': '表单与操作',
    'semanticStates': '状态颜色',
  };
  final group = normalized.split('.').first;
  return context.tr('{mode} · {group} · {token}', <String, Object?>{
    'mode': context.tr(mode),
    'group': context.tr(labels[group] ?? group),
    'token': normalized.substring(group.length + 1),
  });
}
